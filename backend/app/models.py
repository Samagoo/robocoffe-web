"""SQLAlchemy models. Every timestamp is timestamptz, stored in UTC and set by the server.

Columns for later phases (dispatch, arrival, weights, robot ids) are created now but stay
NULL until those phases fill them, so later phases don't need schema migrations.
Dashboard column names (07_datos_dashboard.md) are noted next to each field.
"""
from datetime import datetime

from sqlalchemy import (BigInteger, Computed, DateTime, Float, ForeignKey, Index, SmallInteger,
                        String, Text, func, text)
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import Mapped, mapped_column, relationship

from .db import Base

TS = DateTime(timezone=True)


class Order(Base):
    __tablename__ = "orders"

    id: Mapped[int] = mapped_column(BigInteger, primary_key=True)
    # Folio: P-0001, P-0002 … generated by PostgreSQL from id, so it can never drift
    folio: Mapped[str] = mapped_column(
        String(16),
        Computed("'P-' || CASE WHEN id < 10000 THEN lpad(id::text, 4, '0') ELSE id::text END",
                 persisted=True),
        unique=True,
    )
    product_code: Mapped[str] = mapped_column(String(8))           # Producto (C1/C2/C3)
    table_number: Mapped[int] = mapped_column(SmallInteger)        # Mesa
    distance_m: Mapped[float] = mapped_column(Float)               # Distancia_m, snapshot at order time
    customer_name: Mapped[str | None] = mapped_column(String(80))
    notes: Mapped[str | None] = mapped_column(String(200))
    # Plain text on purpose: allowed values come from order_config.json, not from a DB enum
    status: Mapped[str] = mapped_column(String(40), index=True)
    incident: Mapped[str | None] = mapped_column(String(20))       # Incidencia
    load_weight_g: Mapped[float | None] = mapped_column(Float)     # PesoCarga_g
    delivery_weight_g: Mapped[float | None] = mapped_column(Float) # PesoEntrega_g
    robot_msg_id: Mapped[int | None] = mapped_column(BigInteger, unique=True)  # id= sent in ORDEN

    created_at: Mapped[datetime] = mapped_column(TS, server_default=func.now(), index=True)  # HoraPedido
    updated_at: Mapped[datetime] = mapped_column(TS, server_default=func.now(), onupdate=func.now())
    ready_at: Mapped[datetime | None] = mapped_column(TS)          # HoraListo
    dispatched_at: Mapped[datetime | None] = mapped_column(TS)     # HoraInicioCarga (ORDEN sent)
    arrived_at: Mapped[datetime | None] = mapped_column(TS)        # HoraLlegadaMesa (EVT LLEGO)
    delivered_at: Mapped[datetime | None] = mapped_column(TS)      # HoraEntrega (RETIRADO)
    returned_at: Mapped[datetime | None] = mapped_column(TS)       # HoraRegresoBase

    events: Mapped[list["OrderEvent"]] = relationship(
        back_populates="order", order_by="OrderEvent.id", cascade="all, delete-orphan")


class OrderEvent(Base):
    """Every change of an order's status: the audit trail of the order state machine."""
    __tablename__ = "order_events"

    id: Mapped[int] = mapped_column(BigInteger, primary_key=True)
    order_id: Mapped[int] = mapped_column(ForeignKey("orders.id", ondelete="CASCADE"), index=True)
    from_status: Mapped[str | None] = mapped_column(String(40))    # NULL for the creation event
    to_status: Mapped[str] = mapped_column(String(40))
    cause: Mapped[str | None] = mapped_column(String(80))
    source: Mapped[str] = mapped_column(String(20))                # customer / admin / robot / scale / system
    created_at: Mapped[datetime] = mapped_column(TS, server_default=func.now())

    order: Mapped[Order] = relationship(back_populates="events")


class RobotEvent(Base):
    """Every EVT line received from main_real.py (filled from Phase 4)."""
    __tablename__ = "robot_events"
    __table_args__ = (Index("ix_robot_events_type_received", "event_type", "received_at"),)

    id: Mapped[int] = mapped_column(BigInteger, primary_key=True)
    received_at: Mapped[datetime] = mapped_column(TS, server_default=func.now())  # platform clock (UTC)
    event_type: Mapped[str] = mapped_column(String(20))            # TRANSICION, LLEGO, TRAMO, ERROR, LATIDO
    robot_t: Mapped[float | None] = mapped_column(Float)           # t= field (robot-side seconds)
    robot_msg_id: Mapped[int | None] = mapped_column(BigInteger)   # orden= field (= orders.robot_msg_id)
    order_id: Mapped[int | None] = mapped_column(
        ForeignKey("orders.id", ondelete="SET NULL"), index=True)
    fields: Mapped[dict] = mapped_column(JSONB, server_default=text("'{}'::jsonb"))  # all k=v pairs
    raw: Mapped[str] = mapped_column(Text)                         # the line exactly as received


class ScaleReading(Base):
    """Load-cell readings forwarded by scale_bridge (filled from the scale phase)."""
    __tablename__ = "scale_readings"

    id: Mapped[int] = mapped_column(BigInteger, primary_key=True)
    received_at: Mapped[datetime] = mapped_column(TS, server_default=func.now(), index=True)
    grams: Mapped[float] = mapped_column(Float)
    device_time_ms: Mapped[int | None] = mapped_column(BigInteger)  # Arduino millis(), if sent
    raw: Mapped[str | None] = mapped_column(Text)
    order_id: Mapped[int | None] = mapped_column(
        ForeignKey("orders.id", ondelete="SET NULL"), index=True)
